//! Staged changeset representation for multi-command AI proposals.

use std::collections::HashSet;

use nodavideo_timeline::Sequence;
use serde::{Deserialize, Serialize};
use uuid::Uuid;

use crate::command::{BatchCommand, EditorCommand};
use crate::error::CommandError;

/// Lifecycle status of a staged changeset.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum ChangesetStatus {
    /// Proposed by an agent and awaiting user review.
    Proposed,
    /// Approved by the user and committed into the active timeline.
    Committed,
    /// Rejected by the user and discarded.
    Discarded,
}

/// Summary metrics comparing the current sequence against the speculative staged sequence.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ChangesetDiff {
    pub original_duration_frames: i64,
    pub staged_duration_frames: i64,
    pub original_clip_count: usize,
    pub staged_clip_count: usize,
    pub commands_count: usize,
    pub tracks_affected: usize,
}

/// A staged multi-command edit proposal generated by an AI workflow.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct StagedChangeset {
    /// Unique identifier for this staged changeset.
    pub id: String,
    /// Descriptive name of the workflow (e.g. "Smart Cuts: Remove 4 silent segments").
    pub title: String,
    /// Detailed description of proposed modifications.
    pub description: String,
    /// Associated skill name (e.g. "smart-cuts", "auto-captions", "social-video").
    pub skill_id: Option<String>,
    /// Ordered list of commands comprising the proposed edit.
    pub commands: Vec<EditorCommand>,
    /// Current approval status.
    pub status: ChangesetStatus,
}

impl StagedChangeset {
    /// Create a new staged changeset with a unique UUID.
    pub fn new(title: impl Into<String>, description: impl Into<String>) -> Self {
        Self {
            id: Uuid::new_v4().to_string(),
            title: title.into(),
            description: description.into(),
            skill_id: None,
            commands: Vec::new(),
            status: ChangesetStatus::Proposed,
        }
    }

    /// Attach an originating skill package identifier.
    #[must_use]
    pub fn with_skill(mut self, skill_id: impl Into<String>) -> Self {
        self.skill_id = Some(skill_id.into());
        self
    }

    /// Append an editor command to the proposal.
    pub fn add_command(&mut self, command: EditorCommand) {
        self.commands.push(command);
    }

    /// Apply the staged changeset to a clone of the sequence to produce a speculative preview.
    /// Returns the updated speculative sequence or an error if any command is invalid.
    pub fn apply_speculative(&self, sequence: &Sequence) -> Result<Sequence, CommandError> {
        let mut speculative = sequence.clone();
        for cmd in &self.commands {
            cmd.apply(&mut speculative)?;
        }
        Ok(speculative)
    }

    /// Compute summary diff metrics between the original sequence and the speculative result.
    pub fn compute_diff(&self, original: &Sequence) -> Result<ChangesetDiff, CommandError> {
        let speculative = self.apply_speculative(original)?;

        let original_clip_count: usize = original.tracks.iter().map(|t| t.clips.len()).sum();
        let staged_clip_count: usize = speculative.tracks.iter().map(|t| t.clips.len()).sum();

        let mut affected_tracks = HashSet::new();
        for cmd in &self.commands {
            match cmd {
                EditorCommand::AddClip(c) => {
                    affected_tracks.insert(c.track_id);
                }
                EditorCommand::DeleteClip(c) => {
                    affected_tracks.insert(c.track_id);
                }
                EditorCommand::MoveClip(c) => {
                    affected_tracks.insert(c.from_track);
                    affected_tracks.insert(c.to_track);
                }
                EditorCommand::TrimClip(c) => {
                    affected_tracks.insert(c.track_id);
                }
                EditorCommand::SplitClip(c) => {
                    affected_tracks.insert(c.track_id);
                }
                EditorCommand::UnsplitClip(c) => {
                    affected_tracks.insert(c.track_id);
                }
                EditorCommand::AddTrack(c) => {
                    affected_tracks.insert(c.track.id);
                }
                EditorCommand::DeleteTrack(c) => {
                    affected_tracks.insert(c.track.id);
                }
                EditorCommand::ToggleMute(c) => {
                    affected_tracks.insert(c.track_id);
                }
                EditorCommand::ToggleSolo(c) => {
                    affected_tracks.insert(c.track_id);
                }
                EditorCommand::ToggleLock(c) => {
                    affected_tracks.insert(c.track_id);
                }
                EditorCommand::AddComposition(c) => {
                    affected_tracks.insert(c.track_id);
                }
                EditorCommand::Batch(_) => {}
            }
        }

        Ok(ChangesetDiff {
            original_duration_frames: original.duration_frames(),
            staged_duration_frames: speculative.duration_frames(),
            original_clip_count,
            staged_clip_count,
            commands_count: self.commands.len(),
            tracks_affected: affected_tracks.len(),
        })
    }

    /// Convert the staged changeset into a single atomic BatchCommand for history commit.
    pub fn into_batch_command(self) -> EditorCommand {
        EditorCommand::Batch(BatchCommand {
            name: self.title,
            commands: self.commands,
        })
    }
}
